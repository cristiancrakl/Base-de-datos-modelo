--TABLAS TRIGGER

CREATE SCHEMA IF NOT EXISTS copa
    AUTHORIZATION postgres;

DROP TABLE IF EXISTS COPA.EQUIPO
DROP TABLE IF EXISTS COPA.JUGADOR


CREATE TABLE COPA.EQUIPO(
NRO_EQUIPO VARCHAR(2),
NOMBRE_EQUIPO VARCHAR(20) NOT NULL,
VAL_CURRENT INTEGER,


CONSTRAINT PK_NRO_EQUIPO PRIMARY KEY(NRO_EQUIPO)
);






CREATE TABLE COPA.JUGADOR(

ID_JUGADOR VARCHAR(3),
NOMBRE_JUGADOR VARCHAR(40) NOT NULL,
NRO_EQUIPO VARCHAR(2),


CONSTRAINT PK_ID_JUGADOR PRIMARY KEY (ID_JUGADOR),
CONSTRAINT FK_JUGADOR_EQUIPO FOREIGN KEY (NRO_EQUIPO)
REFERENCES COPA.EQUIPO(NRO_EQUIPO) ON UPDATE CASCADE ON DELETE CASCADE);



