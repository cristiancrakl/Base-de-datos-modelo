CREATE FUNCTION TIENDA_ROPA.SUBTOTAL() RETURNS TRIGGER AS $llenar_subtotal$
DECLARE
	p numeric; d numeric; su numeric;vd numeric;
	BEGIN
		IF NEW.CANTIDAD IS NULL THEN
				RAISE  EXCEPTION '%CANTIDAD NO PUEDE SER NULO', NEW.COD_ARTICULO;
			END IF;
			SELECT VALOR INTO p FROM TIENDA_ROPA.ARTICULO
			WHERE COD_ARTICULO=NEW.COD_ARTICULO;

			d:=NEW.DESCUENTO/100;
			su:=NEW.CANTIDAD*p;
			vd:=ROUND((su*d),2);
			NEW.PRECIO_VENTA:=p;
			NEW.SUB_TOTAL:=(su-vd);
			NEW.VLR_DESCUENTO:=vd;
	RETURN NEW;
	END;
$llenar_subtotal$ LANGUAGE plpgsql;



CREATE TRIGGER llenar_subtotal BEFORE INSERT OR UPDATE ON TIENDA_ROPA.DETALLE
	
FOR EACH ROW EXECUTE PROCEDURE TIENDA_ROPA.SUBTOTAL();



CREATE FUNCTION TIENDA_ROPA.TOTAL() RETURNS TRIGGER AS $llenar_total$
DECLARE 
	sb numeric;
	de numeric;
	BEGIN
		SELECT SUM(SUB_TOTAL), SUM(VLR_DESCUENTO) INTO sb, de
		FROM TIENDA_ROPA.DETALLE
		WHERE CONSECUTIVO = NEW.CONSECUTIVO;

		UPDATE TIENDA_ROPA.FACTURA SET TOTAL=sb, DESCUENTO=de
		WHERE CONSECUTIVO =NEW.CONSECUTIVO;
			RETURN NEW;
		END;
$llenar_total$ LANGUAGE plpgsql;


CREATE TRIGGER llenar_total AFTER INSERT OR UPDATE ON TIENDA_ROPA.DETALLE
	FOR EACH ROW EXECUTE PROCEDURE TIENDA_ROPA.TOTAL();













	
