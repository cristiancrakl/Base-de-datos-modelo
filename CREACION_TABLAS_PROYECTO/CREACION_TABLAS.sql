DROP TABLE IF EXISTS ESPO.AUDI_FACTURA;
DROP TABLE IF EXISTS ESPO.DETALLE_FACTURA;
DROP TABLE IF EXISTS ESPO.FACTURA;
DROP TABLE IF EXISTS ESPO.LECTURA;
DROP TABLE IF EXISTS ESPO.PREDIO;
DROP TABLE IF EXISTS ESPO.SUSCRIPTOR;
DROP TABLE IF EXISTS ESPO.GRUPO_FAMILIAR;
DROP TABLE IF EXISTS ESPO.MEDIDOR;
DROP TABLE IF EXISTS ESPO.BARRIO;
DROP TABLE IF EXISTS ESPO.CONCEPTO;

CREATE TABLE ESPO.CONCEPTO(
ID_TARIFA VARCHAR(10),
PERIODO_VIGENCIA VARCHAR(50) NOT NULL,
ESTRATO INT NOT NULL,
VALOR_CARGO_FIJO NUMERIC(10,2),
VALOR_M3_AGUA NUMERIC(10,2),
TASA_ALCANTARILLADO NUMERIC(5,2),
PORC_SUBSIDIO_CONTRIB NUMERIC(5,2),

CONSTRAINT PK_ID_TARIFA PRIMARY KEY (ID_TARIFA)

);

CREATE TABLE ESPO.BARRIO(
COD_BARRIO VARCHAR(1),
NOMBRE_BARRIO VARCHAR(40) NOT NULL,

CONSTRAINT PK_COD_BARRIO PRIMARY KEY (COD_BARRIO)


);

CREATE TABLE ESPO.MEDIDOR(

NUMERO_MEDIDOR VARCHAR(30),


CONSTRAINT PK_NUMERO_MEDIDOR PRIMARY KEY (NUMERO_MEDIDOR)

);

CREATE TABLE ESPO.GRUPO_FAMILIAR(

ID_GRUPO VARCHAR(10),
NOMBRE_GRUPO VARCHAR(100) NOT NULL,

CONSTRAINT PK_ID_GRUPO PRIMARY KEY (ID_GRUPO)



);


CREATE TABLE ESPO.SUSCRIPTOR (

ID_SUSCRIPTOR VARCHAR (10),
NOMBRES VARCHAR (30) NOT NULL,
APELLIDOS VARCHAR(30) NOT NULL,
TELEFONO VARCHAR(10),
EMAIL VARCHAR(50),
ID_GRUPO VARCHAR(10),

CONSTRAINT PK_ID_SUSCRIPTOR PRIMARY KEY (ID_SUSCRIPTOR),
CONSTRAINT FK_SUSCRIPTOR_GRUPO_FAMILIAR FOREIGN KEY (ID_GRUPO)
REFERENCES ESPO.GRUPO_FAMILIAR(ID_GRUPO)


); 


CREATE TABLE ESPO.PREDIO(

NUMERO_MATRICULA VARCHAR(6),
DIRECCION VARCHAR (150) NOT NULL,
ESTRATO_SOCIOECONOMICO VARCHAR(1) NOT NULL,
TIPO_USO VARCHAR(50) NOT NULL,
ID_SUSCRIPTOR VARCHAR (10),
COD_BARRIO VARCHAR(1),


CONSTRAINT PK_NUMERO_MATRICULA PRIMARY KEY (NUMERO_MATRICULA),
CONSTRAINT FK_PREDIO_SUSCRIPTOR FOREIGN KEY (ID_SUSCRIPTOR)
REFERENCES ESPO.SUSCRIPTOR(ID_SUSCRIPTOR),
CONSTRAINT FK_PREDIO_BARRIO FOREIGN KEY (COD_BARRIO)
REFERENCES ESPO.BARRIO(COD_BARRIO)


);


CREATE TABLE ESPO.LECTURA(

NUMERO_MATRICULA VARCHAR(6),
NUMERO_MEDIDOR VARCHAR(30),
FECHA DATE,
VALOR VARCHAR(50) NOT NULL,
MES VARCHAR (10),
AÑO VARCHAR(1),


CONSTRAINT PK_LECTURA PRIMARY KEY (NUMERO_MATRICULA,NUMERO_MEDIDOR,FECHA),
CONSTRAINT FK_LECTURA_MEDIDOR FOREIGN KEY (NUMERO_MEDIDOR)
REFERENCES ESPO.MEDIDOR(NUMERO_MEDIDOR),
CONSTRAINT FK_LECTURA_PREDIO FOREIGN KEY (NUMERO_MATRICULA)
REFERENCES ESPO.PREDIO(NUMERO_MATRICULA)


);


CREATE TABLE ESPO.FACTURA(

NUMERO_FACTURA VARCHAR(6),
NUMERO_MATRICULA VARCHAR(6),
FECHA_EMISION DATE NOT NULL,
PERIODO_FACTURADO VARCHAR(9) NOT NULL,
FECHA_LIMITE_PAGO DATE NOT NULL,
FECHA_SUSPENSION DATE,
ESTADO VARCHAR(1) NOT NULL,
LECTURA_ANTERIOR VARCHAR(10)NOT NULL,
LECTURA_ACTUAL VARCHAR(10)NOT NULL,
TOTAL FLOAT,


CONSTRAINT PK_NUMERO_FACTURA PRIMARY KEY(NUMERO_FACTURA),
CONSTRAINT FK_LECTURA_PREDIO FOREIGN KEY (NUMERO_MATRICULA)
REFERENCES ESPO.PREDIO(NUMERO_MATRICULA)


);


CREATE TABLE ESPO.DETALLE_FACTURA(

ID_DETALLE VARCHAR(6),
NUMERO_FACTURA VARCHAR(6),
ID_TARIFA VARCHAR(10),
VALOR FLOAT NOT NULL,



CONSTRAINT PK_ID_DETALLE PRIMARY KEY(ID_DETALLE),
CONSTRAINT FK_DETALLEFACTURA_FACTURA FOREIGN KEY (NUMERO_FACTURA)
REFERENCES ESPO.FACTURA(NUMERO_FACTURA),
CONSTRAINT FK_DETALLEFACTURA_CONCEPTO FOREIGN KEY (ID_TARIFA)
REFERENCES ESPO.CONCEPTO(ID_TARIFA)


);

CREATE TABLE ESPO.AUDI_FACTURA(

CONSECUTIVO SERIAL,
NUMERO_FACTURA VARCHAR(6),
NUMERO_MATRICULA VARCHAR(6),
FECHA_EMISION DATE NOT NULL,
PERIODO_FACTURADO VARCHAR(9) NOT NULL,
FECHA_LIMITE_PAGO DATE NOT NULL,
FECHA_SUSPENSION DATE,
ESTADO VARCHAR(1) NOT NULL,
LECTURA_ANTERIOR VARCHAR(10)NOT NULL,
LECTURA_ACTUAL VARCHAR(10)NOT NULL,
TOTAL FLOAT,
FECHA_REGISTRO DATE,
USUARIO VARCHAR(20),
ACCION VARCHAR(1),


CONSTRAINT PK_CONSECUTIVO PRIMARY KEY (CONSECUTIVO),
CONSTRAINT FK_LECTURA_PREDIO FOREIGN KEY (NUMERO_MATRICULA)
REFERENCES ESPO.PREDIO(NUMERO_MATRICULA)


	
);





























