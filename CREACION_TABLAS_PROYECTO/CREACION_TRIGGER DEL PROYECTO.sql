CREATE FUNCTION ESPO.AUDI_FACTURA_FUNC() RETURNS TRIGGER AS  $trg_grabar_audi_factura$
DECLARE 
	BEGIN
		IF (TG_OP='UPDATE') THEN
			INSERT INTO ESPO.AUDI_FACTURA(CONSECUTIVO,NUMERO_FACTURA,NUMERO_MATRICULA,FECHA_EMISION,PERIODO_FACTURADO,FECHA_LIMITE_PAGO,FECHA_SUSPENSION,ESTADO,LECTURA_ANTERIOR,LECTURA_ACTUAL,TOTAL,FECHA_REGISTRO,USUARIO,ACCION)
				VALUES(DEFAULT,OLD.NUMERO_FACTURA,OLD.NUMERO_MATRICULA,OLD.FECHA_EMISION,OLD.PERIODO_FACTURADO,OLD.FECHA_LIMITE_PAGO,OLD.FECHA_SUSPENSION,OLD.ESTADO,OLD.LECTURA_ANTERIOR,OLD.LECTURA_ACTUAL,OLD.TOTAL,CURRENT_TIMESTAMP(0),CURRENT_USER,'U');
			RETURN NEW;
		ELSIF (TG_OP='DELETE') THEN
			INSERT INTO ESPO.AUDI_FACTURA(CONSECUTIVO,NUMERO_FACTURA,NUMERO_MATRICULA,FECHA_EMISION,PERIODO_FACTURADO,FECHA_LIMITE_PAGO,FECHA_SUSPENSION,ESTADO,LECTURA_ANTERIOR,LECTURA_ACTUAL,TOTAL,FECHA_REGISTRO,USUARIO,ACCION)
				VALUES(DEFAULT,OLD.NUMERO_FACTURA,OLD.NUMERO_MATRICULA,OLD.FECHA_EMISION,OLD.PERIODO_FACTURADO,OLD.FECHA_LIMITE_PAGO,OLD.FECHA_SUSPENSION,OLD.ESTADO,OLD.LECTURA_ANTERIOR,OLD.LECTURA_ACTUAL,OLD.TOTAL,CURRENT_TIMESTAMP(0),CURRENT_USER,'D');
			RETURN OLD;
		END IF;
		END
$trg_grabar_audi_factura$ LANGUAGE plpgsql;


--crear el trigger

CREATE TRIGGER trg_grabar_audi_factura BEFORE UPDATE OR DELETE ON ESPO.FACTURA
		FOR EACH ROW EXECUTE PROCEDURE ESPO.AUDI_FACTURA_FUNC();


























				